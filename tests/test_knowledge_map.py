"""`mise run knowledge-map`: research/MAP.md lists every note by folder with its summary."""

from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import Any

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = REPO_ROOT / "python" / "scripts"
HEADER = "<!-- Generated by mise run fix from each note's summary; do not edit. -->"


def _load() -> Any:
    spec = importlib.util.spec_from_file_location("knowledge_map", SCRIPTS / "knowledge_map.py")
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


knowledge_map = _load()


def _note(root: Path, relative: str, text: str = "# Note\n") -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def _summarised(summary: str) -> str:
    return f"---\nsummary: {summary}\n---\n\n# Note\n"


def test_groups_notes_by_folder_with_summaries(tmp_path: Path) -> None:
    _note(tmp_path, "playone-exe/lod.md", _summarised("LOD rules."))
    _note(tmp_path, "formats/auxiliary/map.md", _summarised("`MAP.BIN`: the [Hypothesis] grid."))
    _note(tmp_path, "handbook.md", _summarised("The retail handbook."))
    assert knowledge_map.render_map(tmp_path) == (
        f"{HEADER}\n\n# Research map\n\n"
        "## formats/auxiliary\n\n"
        "- [`formats/auxiliary/map.md`](formats/auxiliary/map.md): `MAP.BIN`: the [Hypothesis] grid.\n\n"
        "## playone-exe\n\n"
        "- [`playone-exe/lod.md`](playone-exe/lod.md): LOD rules.\n\n"
        "## research\n\n"
        "- [`handbook.md`](handbook.md): The retail handbook.\n"
    )


@pytest.mark.parametrize(
    "text",
    [
        "# No frontmatter\n",
        "---\ntitle: Something else\n---\n",
        '---\nsummary: ""\n---\n',
        "---\nsummary: 42\n---\n",
        "---\nsummary: never closed\n",
        "---\nsummary:\n---\n",
    ],
    ids=["no-frontmatter", "no-summary-key", "empty", "not-a-string", "unclosed", "bare-key"],
)
def test_note_without_summary_says_so(tmp_path: Path, text: str) -> None:
    _note(tmp_path, "parity/batch.md", text)
    assert "- [`parity/batch.md`](parity/batch.md): no summary yet\n" in knowledge_map.render_map(
        tmp_path
    )


def test_skips_readme_map_and_non_markdown(tmp_path: Path) -> None:
    _note(tmp_path, "playone-exe/lod.md")
    for relative in (
        "README.md",
        "images/README.md",
        "MAP.md",
        "formats/sod.ksy",
        "formats/pins.toml",
        "images/2026-11-07-72028d1/capture.png",
        "formats/notes.txt",
    ):
        _note(tmp_path, relative)
    assert knowledge_map.note_paths(tmp_path) == [Path("playone-exe/lod.md")]
    listed = [
        line for line in knowledge_map.render_map(tmp_path).splitlines() if line.startswith("- ")
    ]
    assert listed == ["- [`playone-exe/lod.md`](playone-exe/lod.md): no summary yet"]


def test_output_is_stable(tmp_path: Path) -> None:
    for relative in ("parity/z.md", "parity/a.md", "parity/B.md", "formats/sod.md", "handbook.md"):
        _note(tmp_path, relative)
    first = knowledge_map.render_map(tmp_path)
    assert knowledge_map.render_map(tmp_path) == first
    assert [line.split("`")[1] for line in first.splitlines() if line.startswith("- ")] == [
        "formats/sod.md",
        "parity/B.md",
        "parity/a.md",
        "parity/z.md",
        "handbook.md",
    ]
    assert first.endswith("\n")
    assert not first.endswith("\n\n")


def test_check_names_the_stale_map_and_write_refreshes_it(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    _note(tmp_path, "playone-exe/lod.md", _summarised("LOD rules."))
    root = ["--root", str(tmp_path)]
    assert knowledge_map.main(["--check", *root]) == 1
    assert "MAP.md is stale: run mise run fix" in capsys.readouterr().err

    assert knowledge_map.main(["--write", *root]) == 0
    written = (tmp_path / "MAP.md").read_bytes()
    assert written == knowledge_map.render_map(tmp_path).encode("utf-8")
    assert b"\r" not in written
    assert knowledge_map.main(["--check", *root]) == 0

    _note(tmp_path, "playone-exe/lod.md", _summarised("LOD rules, revised."))
    assert knowledge_map.main(["--check", *root]) == 1


def test_a_missing_root_is_a_usage_error(tmp_path: Path) -> None:
    with pytest.raises(SystemExit) as raised:
        knowledge_map.main(["--check", "--root", str(tmp_path / "absent")])
    assert raised.value.code == 2


@pytest.mark.docs
def test_research_map_is_current() -> None:
    research = REPO_ROOT / "research"
    current = (research / "MAP.md").read_bytes().decode("utf-8")
    assert knowledge_map.render_map(research) == current, (
        "research/MAP.md is stale: run mise run fix"
    )
