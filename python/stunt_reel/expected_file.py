"""The generated ``research/parity/expected/<class>.toml`` file: its path, header and format.

Each renderer class has one file of the scores its films are expected to reach (ADR 0053).
``mise run parity-repin`` regenerates one whole, so a take-``main`` merge driver can resolve any
conflict in it; nothing edits it by hand.  :mod:`stunt_reel.references` reads it back.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from stunt_reel.parity_artifacts import LOSS_CLASSES

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence
    from pathlib import Path

    from stunt_reel.references import Expected

__all__ = ["HEADER", "KEYS", "format_values", "path", "render", "toml_string"]

#: The keys of a film's table, in the order a file lists them.
KEYS: tuple[str, ...] = ("ssim", "iou", "crates", "sha256", "all_sha256", "adapter")

#: The comment every generated file opens with, ending in a newline.
HEADER = """\
# GENERATED by `mise run parity-repin`; never edit by hand (ADR 0053).
# A merge or rebase keeps `main`'s copy of this file (the `expected-pins` merge driver); re-measure
# and repin your own class after it, never hand-merge numbers.
#
# The scores each reference film is expected to reach on one renderer class: `gpu` (any adapter
# wgpu does not report as a CPU) or `lavapipe` (any CPU adapter, WARP included). A film's `[<film>]`
# table holds `ssim` and `iou`, a report's `mean_ssim_scored` and `mean_iou_scored`; `crates`, the
# tree measured (`git rev-parse <commit>:crates`, rendered with `crates/` clean), which a squash
# merge keeps when no other `crates/` change lands first, so a clone without the branch commit can
# still compare; `sha256` and `all_sha256`, the row's pins of research/parity/references.toml it
# was measured against; and `adapter`, the adapter's name, since drift is judged only against a
# render on an adapter of that name. Its `[<film>.loss]` table holds the report's
# `mean_loss_by_class_scored`, one key per loss class: `mise run judge` prints a candidate's change
# from it, and drift is not judged on it.
#
# A PR that adopts a change repins the class it measured; the other class's `crates` lags until
# its catch-up repin.
"""


def path(references: Path, renderer: str) -> Path:
    """The class file of *renderer*, beside the *references* file."""
    return references.parent / "expected" / f"{renderer}.toml"


def toml_string(text: str) -> str:
    """*text* as a TOML basic string."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def format_values(expected: Expected) -> tuple[dict[str, str], dict[str, str]]:
    """*expected*'s table values and loss values, as :func:`render` writes them."""
    values = {
        "ssim": f"{expected.ssim:.7f}",
        "iou": f"{expected.iou:.7f}",
        "crates": toml_string(expected.crates),
        "sha256": toml_string(expected.sha256),
        "adapter": toml_string(expected.adapter),
    }
    if expected.all_sha256 is not None:
        values["all_sha256"] = toml_string(expected.all_sha256)
    loss = (
        {}
        if expected.loss is None
        else {name: f"{value:.7f}" for name, value in expected.loss.items()}
    )
    return values, loss


def render(tables: Sequence[tuple[str, Mapping[str, str], Mapping[str, str]]]) -> str:
    """A whole class file: :data:`HEADER`, then each ``(film, values, loss)`` in the order given."""
    parts = [HEADER]
    for film, values, loss in tables:
        lines = [f"[{film}]", *(f"{key} = {values[key]}" for key in KEYS if key in values)]
        parts.append("\n".join(lines) + "\n")
        if loss:
            lines = [
                f"[{film}.loss]",
                *(f"{key} = {loss[key]}" for key in LOSS_CLASSES if key in loss),
            ]
            parts.append("\n".join(lines) + "\n")
    return "\n".join(parts)
