def get_palette_rgb(index: int) -> tuple[int, int, int]:
    """Return the 8-bit integer (R, G, B) tuple for a Mode 13h palette index (0..255)."""
    return MODE_13H_PALETTE[index & 0xFF]


def get_palette_rgb_float(index: int) -> tuple[float, float, float]:
    """Return the normalized floating-point (R, G, B) tuple in [0.0, 1.0]."""
    r, g, b = MODE_13H_PALETTE[index & 0xFF]
    return (r / 255.0, g / 255.0, b / 255.0)


def get_palette_color_0(index: int) -> tuple[float, float, float, float]:
    """Return the normalized (R, G, B, A) tuple in [0.0, 1.0] for glTF COLOR_0 attributes."""
    r, g, b = MODE_13H_PALETTE[index & 0xFF]
    return (r / 255.0, g / 255.0, b / 255.0, 1.0)
