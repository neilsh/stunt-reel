#: Suffix of a film's render store directory under a render root.
CURRENT_SUFFIX = "_current"
#: Maps a byte to 1 when it is not zero, so one ``translate`` counts the set bytes of a XOR.
_NONZERO = bytes(bool(value) for value in range(256))

#: A tick on which the classes differ by more than this many pixels is hot.
HOT_TICK_PIXELS = 500
#: A tick flags when its count rises by more than this over its pinned count.
TICK_FLAG_PIXELS = 1000
#: A film's mean flags when it rises by more than this share of its pinned mean ...
MEAN_RISE_RATIO = 0.25
#: ... and by at least this many pixels per tick.
MEAN_RISE_MIN = 1.0
#: A film flags when its GPU-minus-lavapipe ``mean_ssim_scored`` exceeds this in magnitude.
SSIM_GAP_LIMIT = 0.002
#: A batch is due after this many renderer-changing commits since the pinned tree ...
DUE_COMMITS = 5
#: ... or this many days after the pinned date when at least one has landed.
DUE_DAYS = 7
#: A sweep asks for a GPU check when more than this share of a film's gain lies on hot ticks.
HOT_SHARE_LIMIT = 0.5

#: The comment the generated file opens with, ending in a blank line.
HEADER = """\
# GENERATED by `mise run agreement -- pin`; never edit by hand (#908).
# The index-plane pixels on which the GPU and the canonical lavapipe draw each reference film
# differently, measured on one `crates` tree. `[measured]` names the tree, the date, both
# adapters and drivers, and `accepted` when the pin was made over flags. A film's table holds the
# ticks compared, the ticks differing, the mean and largest differing pixels per tick and the
# largest's tick; `[<film>.hot]` lists every tick differing by more than 500 pixels.

"""


@dataclass(frozen=True)
class Residue:
    """One film's differing-pixel count at each tick its two stores hold."""

    film: str
    ticks: list[int]
    counts: list[int]

    def differing(self) -> int:
        """How many ticks differ at all."""
        return sum(1 for count in self.counts if count)

    def mean(self) -> float:
        """The mean differing pixels per tick compared."""
        return sum(self.counts) / len(self.counts) if self.counts else 0.0

    def largest(self) -> tuple[int, int] | None:
        """The largest count and its tick, or ``None`` when no tick was compared."""
        if not self.counts:
            return None
        at = self.counts.index(max(self.counts))
        return max(self.counts), self.ticks[at]

    def at(self, tick: int) -> int | None:
        """The count at *tick*, or ``None`` when the stores do not hold it."""
        return self.counts[self.ticks.index(tick)] if tick in self.ticks else None


def differing_pixels(left: bytes, right: bytes) -> int:
    """How many pixels' index bytes differ between two planes of one raster."""
    if len(left) != len(right):
        raise ValueError(f"planes of {len(left)} and {len(right)} bytes")
    if left == right:
        return 0
    xor = int.from_bytes(left, "little") ^ int.from_bytes(right, "little")
    return xor.to_bytes(len(left), "little").translate(_NONZERO).count(1)


def film_stores(root: Path) -> dict[str, Path]:
    """Each ``<film>_current`` render store under *root*, keyed by film name."""
    return {
        child.name.removesuffix(CURRENT_SUFFIX): child
        for child in sorted(root.iterdir())
        if child.is_dir() and child.name.endswith(CURRENT_SUFFIX)
    }


def compare(left: RenderStore, right: RenderStore, ticks: list[int]) -> list[int]:
    """The differing-pixel count at each of *ticks*, read from both stores' index planes."""
    return [differing_pixels(left.frame(tick).indices, right.frame(tick).indices) for tick in ticks]


@dataclass(frozen=True)
class FilmAgreement:
    """One film's residue between the classes, as the agreement file records it."""

    film: str
    ticks: int
    differing_ticks: int
    mean: float
    largest: int
    largest_tick: int
    hot: dict[int, int] = field(default_factory=dict)

    @classmethod
    def from_residue(cls, residue: Residue) -> FilmAgreement:
        """*residue* summarised, keeping each tick over :data:`HOT_TICK_PIXELS` as hot."""
        largest = residue.largest() or (0, 0)
        hot = {
            tick: count
            for tick, count in zip(residue.ticks, residue.counts, strict=True)
            if count > HOT_TICK_PIXELS
        }
        return cls(
            film=residue.film,
            ticks=len(residue.ticks),
            differing_ticks=residue.differing(),
            mean=residue.mean(),
            largest=largest[0],
            largest_tick=largest[1],
            hot=hot,
        )


@dataclass(frozen=True)
class Agreement:
    """One measurement of every film, on one tree and one pair of adapters and drivers."""

    crates: str
    date: dt.date
    gpu_adapter: str
    gpu_driver: str
    lavapipe_adapter: str
    lavapipe_driver: str
    films: dict[str, FilmAgreement]
    accepted: str | None = None

    def pair(self) -> tuple[str, str, str, str]:
        """The adapters and drivers measured, which a comparison needs equal."""
        return (self.gpu_adapter, self.gpu_driver, self.lavapipe_adapter, self.lavapipe_driver)


def _string(text: str) -> str:
    """*text* as a TOML basic string."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def format_agreement(agreement: Agreement, order: Sequence[str]) -> str:
    """The whole file for *agreement*: :data:`HEADER`, ``[measured]``, then films in *order*.

    A film *order* names that *agreement* lacks is left out; one *order* lacks goes last, by name.
    """
    measured = [
        "[measured]",
        f"crates = {_string(agreement.crates)}",
        f"date = {agreement.date.isoformat()}",
        f"gpu_adapter = {_string(agreement.gpu_adapter)}",
        f"gpu_driver = {_string(agreement.gpu_driver)}",
        f"lavapipe_adapter = {_string(agreement.lavapipe_adapter)}",
        f"lavapipe_driver = {_string(agreement.lavapipe_driver)}",
    ]
    if agreement.accepted is not None:
        measured.append(f"accepted = {_string(agreement.accepted)}")
    parts = ["\n".join(measured) + "\n"]
    names = [film for film in order if film in agreement.films]
    names += sorted(set(agreement.films) - set(names))
    for name in names:
        film = agreement.films[name]
        parts.append(
            "\n".join(
                [
                    f"[{name}]",
                    f"ticks = {film.ticks}",
                    f"differing_ticks = {film.differing_ticks}",
                    f"mean = {film.mean:.2f}",
                    f"largest = {film.largest}",
                    f"largest_tick = {film.largest_tick}",
                ]
            )
            + "\n"
        )
        if film.hot:
            hot = [f'"{tick}" = {film.hot[tick]}' for tick in sorted(film.hot)]
            parts.append("\n".join([f"[{name}.hot]", *hot]) + "\n")
    return HEADER + "\n".join(parts)


def read_agreement(path: Path) -> Agreement | None:
    """The agreement *path* holds; ``None`` when there is no such file."""
    if not path.is_file():
        return None
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    measured = data.pop("measured")
    films = {
        name: FilmAgreement(
            film=name,
            ticks=table["ticks"],
            differing_ticks=table["differing_ticks"],
            mean=table["mean"],
            largest=table["largest"],
            largest_tick=table["largest_tick"],
            hot={int(tick): count for tick, count in table.get("hot", {}).items()},
        )
        for name, table in data.items()
    }
    return Agreement(
        crates=measured["crates"],
        date=measured["date"],
        gpu_adapter=measured["gpu_adapter"],
        gpu_driver=measured["gpu_driver"],
        lavapipe_adapter=measured["lavapipe_adapter"],
        lavapipe_driver=measured["lavapipe_driver"],
        films=films,
        accepted=measured.get("accepted"),
    )


@dataclass(frozen=True)
class Flag:
    """A change against the pinned agreement worth an issue: which film, why, and which ticks."""

    film: str
    reason: str
    ticks: tuple[int, ...] = ()

    def title(self) -> str:
        """The title of the issue it files: ``Agreement: <film> ticks <a>-<b>``, ``mean`` or ``ssim gap``."""
        if self.ticks:
            return f"Agreement: {self.film} ticks {self.ticks[0]}-{self.ticks[-1]}"
        return f"Agreement: {self.film} {self.reason.split(':', 1)[0]}"


def flags(
    pinned: Agreement | None, measured: Agreement, ssim_gaps: Mapping[str, float]
) -> list[Flag] | str:
    """The flags *measured* raises against *pinned*, or why none can be computed.

    *ssim_gaps* is each film's GPU-minus-lavapipe ``mean_ssim_scored`` on the measured tree.
    A ``str`` comes back when nothing is pinned or an adapter or driver differs: a new pair or a
    first baseline is accepted by hand (``pin --accept``), never flagged film by film.
    """
    if pinned is None:
        return "nothing pinned yet: pin a first baseline with --accept"
    if pinned.pair() != measured.pair():
        return (
            f"the measured pair changed: GPU {pinned.gpu_adapter} ({pinned.gpu_driver}) and "
            f"lavapipe {pinned.lavapipe_adapter} ({pinned.lavapipe_driver}) were pinned, "
            f"GPU {measured.gpu_adapter} ({measured.gpu_driver}) and lavapipe "
            f"{measured.lavapipe_adapter} ({measured.lavapipe_driver}) were measured; "
            "re-baseline with --accept"
        )
    found: list[Flag] = []
    for name, film in measured.films.items():
        before = pinned.films.get(name)
        if before is not None:
            rise = film.mean - before.mean
            if rise >= MEAN_RISE_MIN and rise > MEAN_RISE_RATIO * before.mean:
                found.append(
                    Flag(name, f"mean: {before.mean:.2f} to {film.mean:.2f} pixels per tick")
                )
            risen = tuple(
                tick
                for tick, count in sorted(film.hot.items())
                if count - before.hot.get(tick, HOT_TICK_PIXELS) > TICK_FLAG_PIXELS
            )
            if risen:
                found.append(
                    Flag(name, f"ticks: {len(risen)} rose by over {TICK_FLAG_PIXELS} pixels", risen)
                )
        gap = ssim_gaps.get(name)
        if gap is not None and abs(gap) > SSIM_GAP_LIMIT:
            found.append(Flag(name, f"ssim gap: GPU minus lavapipe {gap:+.7f}"))
    return found


def _git(repo: Path, *args: str) -> str | None:
    """``git -C repo args``'s stdout, stripped; ``None`` when it fails."""
    try:
        done = subprocess.run(  # noqa: S603 - fixed git arguments
            ["git", "-C", str(repo), *args],  # noqa: S607 - git from PATH, as every task
            env=isolated_env(keep_index=False),
            stdin=subprocess.DEVNULL,
            capture_output=True,
            check=False,
        )
    except OSError:
        return None
    if done.returncode != 0:
        return None
    return done.stdout.decode("utf-8", "surrogateescape").strip()


def renderer_commits_since(
    tree: str, *, rev: str = "origin/main", repo: Path = REPO_ROOT
) -> list[str] | None:
    """The first-parent commits of *rev* since the newest whose ``crates`` tree is *tree* that change the renderer, newest first.

    A commit changes the renderer when ``renderer_changes`` finds a path between its first
    parent's ``crates`` tree and its own, or cannot compare them.  ``None`` when git fails or no
    commit has *tree*.
    """
    listing = _git(repo, "rev-list", "--first-parent", rev, "--", "crates")
    if listing is None:
        return None
    found: list[str] = []
    for commit in listing.split():
        own = _git(repo, "rev-parse", f"{commit}:crates")
        if own is None:
            return None
        if own == tree:
            return found
        parent = _git(repo, "rev-parse", "--verify", "--quiet", f"{commit}^1:crates")
        if parent is None or renderer_changes(parent, own, repo) != []:
            found.append(commit)
    return None


def due(pinned: Agreement | None, commits: Sequence[str] | None, today: dt.date) -> str | None:
    """Why a batch is due, or ``None`` when it is not.

    *commits* is :func:`renderer_commits_since` for the pinned tree; ``None`` there (the pinned
    tree is not on the branch) makes a batch due, as does nothing pinned.
    """
    if pinned is None:
        return "nothing pinned yet"
    if commits is None:
        return f"the pinned crates tree {pinned.crates[:7]} is not on the branch"
    if len(commits) >= DUE_COMMITS:
        return f"{len(commits)} renderer commits since {pinned.crates[:7]}"
    age = (today - pinned.date).days
    if commits and age >= DUE_DAYS:
        return f"{len(commits)} renderer commit(s) since {pinned.crates[:7]}, pinned {age} days ago"
    return None


def hot_share(deltas: Mapping[int, float], hot: Mapping[int, int]) -> float | None:
    """The share of the positive SSIM change in *deltas* (by tick) that lies on *hot* ticks.

    ``None`` when no delta is positive.
    """
    gain = sum(delta for delta in deltas.values() if delta > 0)
    if gain <= 0:
        return None
    return sum(delta for tick, delta in deltas.items() if delta > 0 and tick in hot) / gain
