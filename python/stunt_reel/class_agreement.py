"""Class agreement: the index-plane pixels on which lavapipe and the GPU draw a film differently.

Fidelity (capture against lavapipe) is judged and pinned on lavapipe; how far the GPU's render
departs from lavapipe's is measured apart, by ``mise run agreement``, and pinned in
``agreement.toml`` beside the expected scores (#908).  This module counts the residue between two
render-store trees, holds a measurement as :class:`Agreement`, writes and reads its file, and says
which changes against the pinned one are flags and when a new batch is due.  Nothing here renders.
"""

